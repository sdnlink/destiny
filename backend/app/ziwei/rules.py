def get_ganzhi_nayin(stem: str, branch: str) -> str:
    s_idx = STEM_TO_INDEX[stem]
    b_idx = BRANCH_TO_INDEX[branch]
    for idx in range(60):
        if idx % 10 == s_idx and idx % 12 == b_idx:
            return NAYIN_PAIRS[idx // 2]
    return "水二局"

